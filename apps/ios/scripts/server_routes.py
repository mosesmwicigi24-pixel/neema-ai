#!/usr/bin/env python3
"""The server's route table as Swift, for NeemaCore's RouteCoverageTests.

Reads every `@router.<method>("<path>")` in apps/api/app/routers/*.py and the
prefixes main.py mounts each router under (a router mounted twice, like auth
at /api/auth and /api/agent-auth, is listed under both), and writes
Tests/NeemaCoreTests/Support/ServerRoutes.swift. Run it after a backend route
changes:

    python3 apps/ios/scripts/server_routes.py
"""
import glob
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
API = os.path.join(REPO, "apps", "api", "app")
OUT = os.path.join(REPO, "apps", "ios", "NeemaCore", "Tests", "NeemaCoreTests", "Support", "ServerRoutes.swift")


def routes():
    main = open(os.path.join(API, "main.py")).read()
    mounts = {}
    for m in re.finditer(r'include_router\(\s*([\w\.]+)\s*,\s*prefix\s*=\s*"([^"]*)"', main):
        key = m.group(1)
        if key.endswith(".router"):
            key = key[:-7]
        mounts.setdefault(key.split(".")[-1], []).append(m.group(2))
    out = set()
    for f in sorted(glob.glob(os.path.join(API, "routers", "*.py"))):
        name = os.path.basename(f)[:-3]
        src = open(f).read()
        router_prefix = ""
        pm = re.search(r"APIRouter\(([^)]*)\)", src)
        if pm:
            mm = re.search(r'prefix\s*=\s*"([^"]*)"', pm.group(1))
            if mm:
                router_prefix = mm.group(1)
        for app_prefix in mounts.get(name, []):
            for m in re.finditer(r'@router\.(get|post|put|patch|delete|websocket)\(\s*"([^"]+)"', src):
                out.add((m.group(1).upper(), app_prefix + router_prefix + m.group(2), name))
    return sorted(out)


def main():
    rs = routes()
    try:
        sha = subprocess.check_output(["git", "rev-parse", "--short", "HEAD"], cwd=REPO, text=True).strip()
    except Exception:
        sha = "unknown"
    lines = [
        "import Foundation",
        "",
        "/// apps/api/app's route table (method, path as FastAPI serves it): every",
        "/// `@router.<method>(\"…\")` under the prefix main.py mounts its router at.",
        f"/// Generated by apps/ios/scripts/server_routes.py at {sha}; regenerate after a backend route changes.",
        "enum ServerRoutes {",
        "    static let all: [(method: String, path: String)] = [",
    ]
    for method, path, name in rs:
        lines.append(f'        ("{method}", "{path}"),  // {name}')
    lines += ["    ]", "}", ""]
    with open(OUT, "w") as fh:
        fh.write("\n".join(lines))
    print(f"{len(rs)} routes → {os.path.relpath(OUT, REPO)}", file=sys.stderr)


if __name__ == "__main__":
    main()
